-- ---------- clean up (ignore if the objects do not exist yet) ----------
BEGIN
  FOR t IN (SELECT table_name FROM user_tables
             WHERE table_name IN ('ALLOCATION_LOG','FEE_PAYMENTS','ROOM_REQUESTS',
                                  'ALLOCATIONS','APPLICATIONS','ROOMS',
                                  'HOSTEL_BLOCKS','USERS')) LOOP
    EXECUTE IMMEDIATE 'DROP TABLE ' || t.table_name || ' CASCADE CONSTRAINTS PURGE';
  END LOOP;
END;
/

-- ------------------------------ USERS ---------------------------------
-- Students and admins (wardens) share one table, separated by ROLE.
CREATE TABLE users (
  user_id        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name      VARCHAR2(100) NOT NULL,
  email          VARCHAR2(120) NOT NULL CONSTRAINT uq_users_email UNIQUE,
  password_hash  VARCHAR2(64)  NOT NULL,
  role           VARCHAR2(10)  DEFAULT 'STUDENT' NOT NULL
                 CONSTRAINT ck_users_role CHECK (role IN ('ADMIN','STUDENT')),
  gender         CHAR(1)       NOT NULL
                 CONSTRAINT ck_users_gender CHECK (gender IN ('M','F')),
  phone          VARCHAR2(15),
  roll_no        VARCHAR2(20)  CONSTRAINT uq_users_roll UNIQUE,
  course         VARCHAR2(60),
  year_of_study  NUMBER(1)
                 CONSTRAINT ck_users_year CHECK (year_of_study BETWEEN 1 AND 5),
  created_at     DATE DEFAULT SYSDATE NOT NULL
);

-- --------------------------- HOSTEL_BLOCKS ----------------------------
CREATE TABLE hostel_blocks (
  block_id     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  block_name   VARCHAR2(50) NOT NULL CONSTRAINT uq_block_name UNIQUE,
  gender       CHAR(1) NOT NULL
               CONSTRAINT ck_block_gender CHECK (gender IN ('M','F')),
  warden_name  VARCHAR2(100),
  description  VARCHAR2(200)
);

-- ------------------------------- ROOMS --------------------------------
CREATE TABLE rooms (
  room_id    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  block_id   NUMBER NOT NULL CONSTRAINT fk_rooms_block REFERENCES hostel_blocks(block_id),
  room_no    VARCHAR2(10) NOT NULL,
  floor_no   NUMBER(2) DEFAULT 0 NOT NULL,
  room_type  VARCHAR2(10) NOT NULL
             CONSTRAINT ck_room_type CHECK (room_type IN ('SINGLE','DOUBLE','TRIPLE')),
  capacity   NUMBER(1) NOT NULL,
  occupied   NUMBER(1) DEFAULT 0 NOT NULL,
  status     VARCHAR2(12) DEFAULT 'ACTIVE' NOT NULL
             CONSTRAINT ck_room_status CHECK (status IN ('ACTIVE','MAINTENANCE')),
  CONSTRAINT uq_room     UNIQUE (block_id, room_no),
  CONSTRAINT ck_room_occ CHECK (occupied BETWEEN 0 AND capacity),
  CONSTRAINT ck_room_cap CHECK (   (room_type = 'SINGLE' AND capacity = 1)
                                OR (room_type = 'DOUBLE' AND capacity = 2)
                                OR (room_type = 'TRIPLE' AND capacity = 3))
);

-- ---------------------------- APPLICATIONS ----------------------------
CREATE TABLE applications (
  app_id           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id       NUMBER NOT NULL CONSTRAINT fk_app_student REFERENCES users(user_id),
  preferred_block  NUMBER CONSTRAINT fk_app_block REFERENCES hostel_blocks(block_id),
  preferred_type   VARCHAR2(10) NOT NULL
                   CONSTRAINT ck_app_type CHECK (preferred_type IN ('SINGLE','DOUBLE','TRIPLE')),
  status           VARCHAR2(12) DEFAULT 'PENDING' NOT NULL
                   CONSTRAINT ck_app_status CHECK (status IN
                     ('PENDING','ALLOTTED','WAITLISTED','REJECTED','CANCELLED')),
  remarks          VARCHAR2(200),
  applied_on       DATE DEFAULT SYSDATE NOT NULL,
  decided_on       DATE
);

-- ----------------------------- ALLOCATIONS ----------------------------
CREATE TABLE allocations (
  alloc_id     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id   NUMBER NOT NULL CONSTRAINT fk_alloc_student REFERENCES users(user_id),
  room_id      NUMBER NOT NULL CONSTRAINT fk_alloc_room REFERENCES rooms(room_id),
  app_id       NUMBER CONSTRAINT fk_alloc_app REFERENCES applications(app_id),
  alloc_date   DATE DEFAULT SYSDATE NOT NULL,
  vacate_date  DATE,
  status       VARCHAR2(10) DEFAULT 'ACTIVE' NOT NULL
               CONSTRAINT ck_alloc_status CHECK (status IN ('ACTIVE','VACATED'))
);

-- A student can hold at most ONE active allocation (function-based unique index)
CREATE UNIQUE INDEX ux_alloc_one_active
  ON allocations (CASE WHEN status = 'ACTIVE' THEN student_id END);

-- ----------------------------- FEE_PAYMENTS ---------------------------
CREATE TABLE fee_payments (
  pay_id    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  alloc_id  NUMBER NOT NULL CONSTRAINT fk_pay_alloc REFERENCES allocations(alloc_id),
  amount    NUMBER(10,2) NOT NULL CONSTRAINT ck_pay_amt CHECK (amount > 0),
  pay_mode  VARCHAR2(12) NOT NULL
            CONSTRAINT ck_pay_mode CHECK (pay_mode IN ('UPI','CARD','CASH','NETBANKING')),
  txn_ref   VARCHAR2(40),
  paid_on   DATE DEFAULT SYSDATE NOT NULL
);

-- ----------------------------- ROOM_REQUESTS --------------------------
-- Vacate / room-change requests raised by students, approved by admin.
CREATE TABLE room_requests (
  req_id       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id   NUMBER NOT NULL CONSTRAINT fk_req_student REFERENCES users(user_id),
  req_type     VARCHAR2(10) NOT NULL
               CONSTRAINT ck_req_type CHECK (req_type IN ('VACATE','CHANGE')),
  new_type     VARCHAR2(10)
               CONSTRAINT ck_req_newtype CHECK (new_type IN ('SINGLE','DOUBLE','TRIPLE')),
  reason       VARCHAR2(300) NOT NULL,
  status       VARCHAR2(10) DEFAULT 'PENDING' NOT NULL
               CONSTRAINT ck_req_status CHECK (status IN ('PENDING','APPROVED','REJECTED')),
  admin_note   VARCHAR2(200),
  created_at   DATE DEFAULT SYSDATE NOT NULL,
  resolved_at  DATE
);

-- ---------------------------- ALLOCATION_LOG --------------------------
-- Audit trail, filled automatically by triggers.
CREATE TABLE allocation_log (
  log_id      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  alloc_id    NUMBER,
  student_id  NUMBER,
  room_id     NUMBER,
  action      VARCHAR2(20),
  details     VARCHAR2(200),
  log_time    TIMESTAMP DEFAULT SYSTIMESTAMP,
  db_user     VARCHAR2(60) DEFAULT USER
);

-- ------------------------------ INDEXES -------------------------------
CREATE INDEX ix_rooms_block      ON rooms (block_id);
CREATE INDEX ix_app_student      ON applications (student_id);
CREATE INDEX ix_app_status       ON applications (status);
CREATE INDEX ix_alloc_room       ON allocations (room_id);
CREATE INDEX ix_pay_alloc        ON fee_payments (alloc_id);
CREATE INDEX ix_req_student      ON room_requests (student_id);

-- ------------------------------- VIEWS --------------------------------
CREATE OR REPLACE VIEW v_room_details AS
SELECT r.room_id, r.room_no, r.floor_no, r.room_type, r.capacity, r.occupied,
       r.capacity - r.occupied AS free_beds, r.status,
       b.block_id, b.block_name, b.gender
  FROM rooms r
  JOIN hostel_blocks b ON b.block_id = r.block_id;

CREATE OR REPLACE VIEW v_active_allocations AS
SELECT a.alloc_id, a.alloc_date, a.student_id,
       u.full_name, u.email, u.roll_no, u.course, u.year_of_study, u.phone, u.gender,
       r.room_id, r.room_no, r.room_type, r.floor_no,
       b.block_id, b.block_name
  FROM allocations a
  JOIN users u          ON u.user_id  = a.student_id
  JOIN rooms r          ON r.room_id  = a.room_id
  JOIN hostel_blocks b  ON b.block_id = r.block_id
 WHERE a.status = 'ACTIVE';

CREATE OR REPLACE VIEW v_block_occupancy AS
SELECT b.block_id, b.block_name, b.gender, b.warden_name, b.description,
       COUNT(r.room_id)                                               AS total_rooms,
       NVL(SUM(CASE WHEN r.status = 'ACTIVE' THEN r.capacity END), 0) AS total_beds,
       NVL(SUM(r.occupied), 0)                                        AS occupied_beds
  FROM hostel_blocks b
  LEFT JOIN rooms r ON r.block_id = b.block_id
 GROUP BY b.block_id, b.block_name, b.gender, b.warden_name, b.description;
