package com.hostel.dao;

import java.math.BigDecimal;
import java.sql.CallableStatement;
import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Types;
import java.util.ArrayList;
import java.util.List;

import com.hostel.model.Allocation;
import com.hostel.model.Payment;
import com.hostel.model.User;
import com.hostel.util.DBUtil;

/** Active allocations, roommates, fee payments and vacating. */
public class AllocationDAO {

    private static final String SELECT =
            "SELECT v.*, hostel_pkg.calc_fee(v.room_type) fee_total, "
          + "       hostel_pkg.fee_due(v.alloc_id) fee_due "
          + "  FROM v_active_allocations v ";

    public Allocation findActiveByStudent(int studentId) throws SQLException {
        try (Connection con = DBUtil.getConnection();
             PreparedStatement ps = con.prepareStatement(SELECT + "WHERE v.student_id = ?")) {
            ps.setInt(1, studentId);
            try (ResultSet rs = ps.executeQuery()) {
                return rs.next() ? map(rs) : null;
            }
        }
    }

    public List<Allocation> listActive() throws SQLException {
        List<Allocation> list = new ArrayList<>();
        try (Connection con = DBUtil.getConnection();
             PreparedStatement ps = con.prepareStatement(
                     SELECT + "ORDER BY v.block_name, LPAD(v.room_no, 10, '0'), v.full_name");
             ResultSet rs = ps.executeQuery()) {
            while (rs.next()) {
                list.add(map(rs));
            }
        }
        return list;
    }

    public List<User> roommates(int roomId, int excludeStudentId) throws SQLException {
        String sql = "SELECT u.user_id, u.full_name, u.email, u.role, u.gender, u.phone, u.roll_no, "
                   + "       u.course, u.year_of_study, u.created_at "
                   + "  FROM allocations a JOIN users u ON u.user_id = a.student_id "
                   + " WHERE a.room_id = ? AND a.status = 'ACTIVE' AND a.student_id <> ? "
                   + " ORDER BY u.full_name";
        List<User> list = new ArrayList<>();
        try (Connection con = DBUtil.getConnection();
             PreparedStatement ps = con.prepareStatement(sql)) {
            ps.setInt(1, roomId);
            ps.setInt(2, excludeStudentId);
            try (ResultSet rs = ps.executeQuery()) {
                while (rs.next()) {
                    list.add(UserDAO.map(rs));
                }
            }
        }
        return list;
    }

    public List<Payment> payments(int studentId) throws SQLException {
        String sql = "SELECT p.* FROM fee_payments p JOIN allocations a ON a.alloc_id = p.alloc_id "
                   + "WHERE a.student_id = ? ORDER BY p.paid_on DESC, p.pay_id DESC";
        List<Payment> list = new ArrayList<>();
        try (Connection con = DBUtil.getConnection();
             PreparedStatement ps = con.prepareStatement(sql)) {
            ps.setInt(1, studentId);
            try (ResultSet rs = ps.executeQuery()) {
                while (rs.next()) {
                    Payment p = new Payment();
                    p.setPayId(rs.getInt("pay_id"));
                    p.setAllocId(rs.getInt("alloc_id"));
                    p.setAmount(rs.getBigDecimal("amount"));
                    p.setPayMode(rs.getString("pay_mode"));
                    p.setTxnRef(rs.getString("txn_ref"));
                    p.setPaidOn(rs.getTimestamp("paid_on"));
                    list.add(p);
                }
            }
        }
        return list;
    }

    /** @return the transaction reference generated by the procedure */
    public String payFee(int allocId, BigDecimal amount, String mode) throws SQLException {
        try (Connection con = DBUtil.getConnection();
             CallableStatement cs = con.prepareCall("{call hostel_pkg.pay_fee(?, ?, ?, ?, ?)}")) {
            cs.setInt(1, allocId);
            cs.setBigDecimal(2, amount);
            cs.setString(3, mode);
            cs.registerOutParameter(4, Types.NUMERIC);
            cs.registerOutParameter(5, Types.VARCHAR);
            cs.execute();
            return cs.getString(5);
        }
    }

    /** @return app id of the waitlisted student who received the freed bed, or null */
    public Integer vacate(int studentId) throws SQLException {
        try (Connection con = DBUtil.getConnection();
             CallableStatement cs = con.prepareCall("{call hostel_pkg.vacate_room(?, ?)}")) {
            cs.setInt(1, studentId);
            cs.registerOutParameter(2, Types.NUMERIC);
            cs.execute();
            int next = cs.getInt(2);
            return cs.wasNull() ? null : next;
        }
    }

    private static Allocation map(ResultSet rs) throws SQLException {
        Allocation a = new Allocation();
        a.setAllocId(rs.getInt("alloc_id"));
        a.setAllocDate(rs.getTimestamp("alloc_date"));
        a.setStudentId(rs.getInt("student_id"));
        a.setStudentName(rs.getString("full_name"));
        a.setEmail(rs.getString("email"));
        a.setRollNo(rs.getString("roll_no"));
        a.setCourse(rs.getString("course"));
        a.setYearOfStudy(DaoUtil.getInteger(rs, "year_of_study"));
        a.setPhone(rs.getString("phone"));
        a.setRoomId(rs.getInt("room_id"));
        a.setRoomNo(rs.getString("room_no"));
        a.setRoomType(rs.getString("room_type"));
        a.setFloorNo(rs.getInt("floor_no"));
        a.setBlockName(rs.getString("block_name"));
        a.setFeeTotal(rs.getBigDecimal("fee_total"));
        a.setFeeDue(rs.getBigDecimal("fee_due"));
        return a;
    }
}
